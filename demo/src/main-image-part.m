#import "import-private.h"

#include <unistd.h>


static MulleUIResourceStorageKeyDefine( tardbeaver);

static BOOL   drawStuff( CGGraphicsLayer *layer, CGContext *_context)
{
   CGContext          *context = _context;
   CGRect             rect;
   CGRect             patternRect;
   struct NVGpaint    imgPaint;
   struct NVGcontext  *vg;
   CGSize             imageSize;
   CGImage            *image;

   vg    = CGContextGetNVGContext( context);
   image = [context resourceForKey:MulleUIResourceStorageKey( tardbeaver)];
   if( ! image)
   {
      image = [[[CGImage alloc] initWithContentsOfFileUTF8String:"tardbeaver.png"
                                                 textureFlags:0 //NVG_IMAGE_REPEATX|NVG_IMAGE_REPEATY
                                                      context:context] autorelease];
      if( ! image)
      {
         fprintf( stderr, "could not load tardbeaver.png\n");
         _exit( 1);
      }
      [context setResource:image
                    forKey:MulleUIResourceStorageKey( tardbeaver)];
   }

   imageSize   = [image size];
   patternRect = CGRectMake( imageSize.width / 4.0,
                             0,
                             imageSize.width / 2.0,
                             imageSize.height / 2.0);
   rect        = [layer canvas];

   [image drawRect:rect
          fromRect:patternRect
           options:NULL
           context:context];
   return( YES);
}



static void   setupSceneInWindow( UIWindow *window)
{
   CGRect   frame;
   UIView   *view;
   UIView   *contentView;

   contentView = [window contentView];
   frame       = [contentView contentRect];
   frame       = UIEdgeInsetsInsetRect( frame, UIEdgeInsetsMake( 10, 10, 10, 10));

   // this works in one-window scenarios well, where there is only one
   // context.
   view = [UIView viewWithFrame:frame];
   [(CGGraphicsLayer *) [view layer] setDrawCallback:drawStuff];
   [(CGGraphicsLayer *) [view layer] setBackgroundColor:CGColorMakeWithRGBA( 0.33, 0.33, 0.33, 1.0)];

   [contentView addSubview:view];
}



int   main( int argc, char *argv[])
{
   UIWindow        *window;
   UIApplication   *app;

   app = [UIApplication sharedInstance];
   {
      window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 800.0, 600.0)];
      [window setBackgroundColor:CGColorMakeWithRGBA( 0.5, 0.5, 0.5, 1.0)];
      setupSceneInWindow( window);

      [app addWindow:window];
   }
   return( [app runApp]);
}



