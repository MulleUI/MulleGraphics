#import "import-private.h"

#include <unistd.h>
#include <math.h>


static CGPath   *createWheelPath( CGRect rect, NSUInteger numPetals)
{
   CGMutablePathRef   path;
   CGPoint            center;
   CGFloat            angleIncrement;
   CGFloat            radius;
   NSUInteger         i;
   CGFloat            startRadians; 
   CGFloat            endRadians;   

   if( numPetals < 1)
      numPetals = 1;

   angleIncrement = CA_2xPI / numPetals; // Divide a full circle by the number of petals

   path   = CGPathCreateMutable();
   center = CGRectGetCenterPoint( rect);
   radius = CGRectGetMinimumSize( rect) / 2.0;

   for( i = 0; i < numPetals; i++) 
   {
      CGPathMoveToPoint( path, center);

      startRadians = i * angleIncrement;
      endRadians   = (i + 1) * angleIncrement;
      CGPathAddArcWithCenterPoint( path, 
                                   center, 
                                   radius, 
                                   CARadiansToAngle( startRadians), 
                                   CARadiansToAngle( endRadians), 
                                   NVG_CW);
   }

   CGPathCloseSubpath( path);
   return( path);
}


static void   setupSceneInWindow( UIWindow *window)
{
   CAShapeLayer   *layer;
   CGRect         frame;
   UIView         *view;
   UIView         *contentView;
   CGPath         *path;
   CGFloat        strokeWidth;
   CGRect         rect;

   strokeWidth = 3.0;

   contentView = [window contentView];
   frame       = CGRectInset( [contentView contentRect], 80, 60);
   layer       = [CAShapeLayer layerWithFrame:frame];
   rect        = CGRectInset( [layer canvas], strokeWidth / 2.0, strokeWidth / 2.0);
   path        = createWheelPath( rect, 12);

   [layer setPath:path];
   [layer setStrokeWidth:strokeWidth];
   [layer setStrokePaint:[CGPaint paintWithColor:CGColorMakeIndigo()]];

   view        = [UIView viewWithLayer:layer];
   [contentView addSubview:view];
}


int   main( int argc, char *argv[])
{
   UIWindow        *window;
   UIApplication   *app;
   NSUInteger      styleMask;

   app = [UIApplication sharedInstance];
   {
      styleMask = UIWindowStyleMaskDefault;
      window    = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 400.0, 300.0)
                            titleUTF8String:"Demo"
                                  styleMask:styleMask];
      setupSceneInWindow( window);
      [app addWindow:window];
   }
   return( [app runApp]);
}



