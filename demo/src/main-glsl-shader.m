#import <MulleUICore/MulleUICore.h>



static char *vertexShaderSource ="#version 330 core\n"
    "precision mediump float;\n"
    "layout (location = 0) in vec3 aPos;\n"
    "void main()\n"
    "{\n"
    "   gl_Position = vec4(aPos, 1.0);\n"
    "}\0";

static char *fragmentShaderSource = "#version 330 core\n"
    "precision mediump float;\n"
    "uniform vec4 ourColor;\n"
    "out vec4 FragColor;\n"
    "void main()\n"
    "{\n"
    "   FragColor = ourColor;\n"
    "}\n\0";


@interface DemoLayer : CAOpenGLLayer
{
   unsigned int   VBO, VAO;
   unsigned int   shaderProgram;
}
@end


@implementation DemoLayer

- (void) initShaderProgramWithContext:(CGContext *) context
{
   shaderProgram = [context compileVertexShader:vertexShaderSource
                                 fragmentShader:fragmentShaderSource
                                 nameUTF8String:"monochrome"];
 }


- (void) initVertexBuffer
{
    // set up vertex data (and buffer(s)) and configure vertex attributes
    // ------------------------------------------------------------------
    static float vertices[] = {
         0.5f, -0.5f, 0.0f,  // bottom right
        -0.5f, -0.5f, 0.0f,  // bottom left
         0.0f,  0.5f, 0.0f   // top
    };

    glGenVertexArrays(1, &VAO);
    glGenBuffers(1, &VBO);
    // bind the Vertex Array Object first, then bind and set vertex buffer(s), and then configure vertex attributes(s).
    glBindVertexArray(VAO);

    glBindBuffer(GL_ARRAY_BUFFER, VBO);
    glBufferData(GL_ARRAY_BUFFER, sizeof(vertices), vertices, GL_STATIC_DRAW);

    glVertexAttribPointer(0, 3, GL_FLOAT, GL_FALSE, 3 * sizeof(float), (void*)0);
    glEnableVertexAttribArray(0);

    // You can unbind the VAO afterwards so other VAO calls won't accidentally modify this VAO, but this rarely happens. Modifying other
    // VAOs requires a call to glBindVertexArray anyways so we generally don't unbind VAOs (nor VBOs) when it's not directly necessary.
    // glBindVertexArray(0);
}


- (void) drawOpenGLWithContext:(CGContext *) context;
{
   float    timeValue;
   float   greenValue;
   GLint   vertexColorLocation;
   GLfloat rgba[ 4];

   if( ! VAO)
      [self initVertexBuffer];
   if( ! shaderProgram)
      [self initShaderProgramWithContext:context];

   glBindVertexArray(VAO);
   glUseProgram(shaderProgram);

   // update shader uniform
   timeValue  = glfwGetTime();
   greenValue = sin(timeValue) / 2.0f + 0.5f;

   vertexColorLocation = glGetUniformLocation(shaderProgram, "ourColor");

   rgba[ 0] = 0.0;
   rgba[ 1] = greenValue;
   rgba[ 2] = 0.0;
   rgba[ 3] = 1.0;

   // MEMO: glUniform4f does not work !!!
   glUniform4fv( vertexColorLocation, 1, rgba);

   // render the triangle
   glDrawArrays(GL_TRIANGLES, 0, 3);
}


- (void) finalize
{
   glDeleteVertexArrays( 1, &VAO);
   glDeleteBuffers( 1, &VBO);
   glDeleteProgram( shaderProgram);

   [super finalize];
}

@end


int   main( int argc, char *argv[])
{
   UIApplication   *app;
   UIWindow        *window;
   CALayer         *layer;

   app = [UIApplication sharedInstance];
   {
      layer  = [DemoLayer layerWithFrame:CGRectMake( 10, 10, 620, 380)];
      window = [UIWindow windowWithLayer:layer
                         titleUTF8String:NULL];
      [window setFrameRateHz:30.0];
      [app addWindow:window];
   }
   return( [app run]);
}



