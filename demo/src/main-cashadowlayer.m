#import "import-private.h"

#include <unistd.h>



static UIWindowDisplayBits   changeShadow( UIWindow *window,
                                           id <UIGraphicsContext> context,
                                           struct CGFrameInfo *info,
                                           UIWindowDisplayBits displayBits)
{
   CAShadowLayer      *layer;
   UIView             *view;
   UIView             *contentView;
   MulleEdgeInsets    insets;
   CGFloat            blur;

   contentView    = [window contentView];
   view           = [contentView subviewWithTag:1848];
   layer          = (CAShadowLayer *) [view layer];

   insets.top     = roundf( CGFloatMakeRandomMinMax( -10.0, +10.0));
   insets.left    = roundf( CGFloatMakeRandomMinMax( -10.0, +10.0));
   insets.bottom  = roundf( CGFloatMakeRandomMinMax( -10.0, +10.0));
   insets.right   = roundf( CGFloatMakeRandomMinMax( -10.0, +10.0));

   blur = 0.0;
   blur = fmaxf( blur, insets.top);
   blur = fmaxf( blur, insets.left);
   blur = fmaxf( blur, insets.bottom);
   blur = fmaxf( blur, insets.right);

   MulleUICLog( "%s", MulleEdgeInsetsUTF8String( insets));
   [layer setShadowInsets:insets];
   [layer setShadowBlur:blur];
//   [view setNeedsDisplay];

   return( displayBits);
}


static void   setupSceneInWindow( UIWindow *window)
{
   CAShadowLayer   *layer;
   CGRect          frame;
   UIView          *view;
   UIView          *contentView;

   contentView = [window contentView];
   frame       = CGRectInset( [contentView contentRect], 30, 30);

   // though a UIView has a dedicated shadowLayer (ATM) let's just use one
   // "manually"
   layer = [CAShadowLayer layerWithFrame:frame];
   [layer setShadowColor:CGColorBySettingAlpha( CGColorMakeLime(), 0.5)];
   view  = [UIView viewWithLayer:layer];

   // important to see something!
   [view setClipsToBounds:NO];
   [view setTag:1848];
   [contentView addSubview:view];
}


int   main( int argc, char *argv[])
{
   UIWindow        *window;
   UIApplication   *app;
   NSUInteger      styleMask;

   app = [UIApplication sharedInstance];
   {
      styleMask = UIWindowStyleMaskDefault;
      window    = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 400.0, 300.0)
                            titleUTF8String:"Demo"
                                  styleMask:styleMask];
      setupSceneInWindow( window);
      [window setFrameRateHz:0.5f];
      [window setWillRenderFrameCallback:changeShadow];
      [app addWindow:window];
   }
   return( [app runApp]);
}



